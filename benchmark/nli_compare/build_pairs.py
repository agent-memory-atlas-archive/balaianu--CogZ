def main():
    out = []
    for f in FACTS:
        out.append({"premise": f["p"], "hypothesis": f["e"], "label": "entailment"})
        out.append({"premise": f["p"], "hypothesis": f["c"], "label": "contradiction"})
    for p, h in NEUTRALS:
        out.append({"premise": p, "hypothesis": h, "label": "neutral"})

    dst = Path(__file__).parent / "pairs_extra.jsonl"
    with dst.open("w") as fh:
        for r in out:
            fh.write(json.dumps(r) + "\n")
    from collections import Counter
    print(len(out), "pairs ->", dst.name, Counter(r["label"] for r in out))


if __name__ == "__main__":
    main()
